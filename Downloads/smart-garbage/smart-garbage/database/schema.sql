CREATE DATABASE IF NOT EXISTS smart_garbage CHARACTER SET utf8mb4;
USE smart_garbage;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(80) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  phone VARCHAR(20),
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','collector','resident') NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE bins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  bin_code VARCHAR(20) NOT NULL UNIQUE,
  location VARCHAR(100) NOT NULL,
  resident_id INT NULL,
  distance_cm INT NOT NULL DEFAULT 97,
  fill_percent TINYINT NOT NULL DEFAULT 3,
  alerted TINYINT(1) NOT NULL DEFAULT 0,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (resident_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE readings (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  bin_id INT NOT NULL,
  distance_cm INT NOT NULL,
  fill_percent TINYINT NOT NULL,
  recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (bin_id) REFERENCES bins(id) ON DELETE CASCADE
);

CREATE TABLE notifications (
  id INT AUTO_INCREMENT PRIMARY KEY,
  bin_id INT NOT NULL,
  message VARCHAR(200) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (bin_id) REFERENCES bins(id) ON DELETE CASCADE
);

CREATE TABLE collections (
  id INT AUTO_INCREMENT PRIMARY KEY,
  bin_id INT NOT NULL,
  collector_id INT NOT NULL,
  fill_before TINYINT NOT NULL,
  collected_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (bin_id) REFERENCES bins(id) ON DELETE CASCADE,
  FOREIGN KEY (collector_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE invoices (
  id INT AUTO_INCREMENT PRIMARY KEY,
  invoice_no VARCHAR(20) NOT NULL UNIQUE,
  resident_id INT NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  status ENUM('Unpaid','Paid') NOT NULL DEFAULT 'Unpaid',
  issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (resident_id) REFERENCES users(id) ON DELETE CASCADE
);
